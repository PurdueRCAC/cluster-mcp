"""Review cycle 1, F1 and F3: every refusal the tool rules can make is held by the suite.

    uv run python -I spec/capability-tool-objects-inert/remediation/F1-tool-rule-sweep.py MODE [ARGS]
                                                                               from the worktree root

A mutant sweep over every decision of the tool-rule code in `core/capabilities.py`: the functions of
`FUNCTIONS`, the tables of `TABLES`, and the load's two decisions of the registry. Generated by walking
each function's syntax tree, one change at a time:

- each `if`, `elif`, conditional expression and comprehension condition made always true, never true,
  and negated; each `while` never entered;
- each `and`/`or` without each operand, and with the other operator;
- each comparison negated (`is`/`is not`, `in`/`not in`, `==`/`!=`);
- each `return` of an answer turned (a cause to None, None to a cause, `False`/`True` to the other);
- each `continue`, and each call made as a statement (a push, a record, the warning), dropped;
- each `except` arm made to catch nothing;
- each type of `_RETURN_CLASSES` and `_RETURN_ALIASES` dropped; each rule of `TOOL_RULES` made to check
  nothing, and each field the default rule decides left to the rule for a field no rule names;
- each of the load's two decisions of the registry never and always taken.

A mutated function is written back as `ast.unparse` gives it, in place of its own text; the control
(`control`) writes every function back unmutated and must pass, so the rewrite alone kills nothing. A
change that leaves the function's tree as it was is no mutant and is not counted.

Each mutant is planted in a scratch copy by the repo runner (`tests/mutants.py`'s `apply`), and the
targets (`TARGETS`: the capability loader's tests, the served surface and the registry) run against it in a child pytest under `bin/sandbox.sh`, stopping at the first failure,
in the era given. Verdicts: `killed` (a test failed: an assertion, the first named), `error` (only an
error, no failure: not a kill, unviable), `survived`, `timeout` (the per-mutant bound, `BOUND`), `harness`.
A survivor recorded in `EQUIVALENT` (with why) is `equivalent`.

Modes:
- `list`: every mutant id, and the count.
- `control ERA`: the unmutated rewrite, run against the targets in ERA; must pass.
- `run ERA K/N [LOG]`: shard K of N (by a stable hash of the id) in ERA (`handshake` or `modern`), two
  children at a time; a line per mutant on stdout and in LOG, which the run starts afresh. Exits 1 when a mutant survives
  unrecorded, errors, times out or the harness fails.
- `ids ERA ID...`: the mutants named, in ERA, one at a time (a cheap re-run of survivors).
- `report LOG...`: the table over the logs given: each mutant's verdict in each era, and the counts.
  Exits 1 unless every mutant ran in both eras, each killed or recorded equivalent.

Footprint: at most two children at a time, each one pytest process under bin/sandbox.sh, under 1 GB in
all; a killed mutant takes about 3 to 13 s, a survivor about 40 s (the targets whole, under the sandbox):
453 mutants, about 40 min an era with two children on a shared host (2026-11-12).
"""

