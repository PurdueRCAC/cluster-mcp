# Survivors that change no behaviour, each with why.
EQUIVALENT: dict[str, str] = {
    '_same:BoolOp@1:drop0':
        'a `bool` is one of two singletons: an equal pair is one object, taken by `a is b` before this test, '
        'and an unequal pair falls to "anything else by identity", False, the answer `==` gives.',
    '_return_type_violation:BoolOp@1:drop1':
        "`inspect.Signature.empty` is the class `inspect._empty`, of metaclass exactly `type`, its namespace "
        "keyed by `str` and its `__module__` the `str` 'inspect': the class branch accepts it with the same "
        "answer, reading it only through `type`'s own descriptors.",
    '_return_type_violation:IfExp@1:always':
        "the alias it adds `__origin__` for is `typing.Union` (3.14), whose `__origin__` is the class "
        "`typing.Union`, of metaclass exactly `type`, namespace keyed by `str`, `__module__` 'typing': "
        'walking it accepts it, so the answer is the same and nothing of a capability is read.',
    '_RETURN_ALIASES:drop:typing._UnionGenericAlias':
        'on Python 3.14 (`requires-python >=3.14`) `typing._UnionGenericAlias` is a deprecated shim whose call '
        'returns a `typing.Union`: no `typing` or FastMCP path gives a value of exactly that type. Only a value '
        'built by `object.__new__` tells the two apart: accepted with the entry (its state read through its '
        'instance dictionary, as for every alias), refused without it; inert either way.',
}


@dataclass(frozen=True)
class Mutant:
    id: str
    old: str
    new: str
    what: str


def _negated(op: ast.cmpop) -> ast.cmpop | None:
    pairs = {ast.Is: ast.IsNot, ast.IsNot: ast.Is, ast.In: ast.NotIn, ast.NotIn: ast.In, ast.Eq: ast.NotEq,
             ast.NotEq: ast.Eq, ast.Lt: ast.GtE, ast.GtE: ast.Lt, ast.Gt: ast.LtE, ast.LtE: ast.Gt}
    kind = pairs.get(type(op))
    return kind() if kind else None


def _variants(node: ast.AST, parent: ast.AST | None) -> list[tuple[str, object]]:
    """Each change of `node` as (label, replacement): an AST node to put in its place, or None to drop it
    (a statement), or a callable that edits it in place."""
    out: list[tuple[str, object]] = []
    if isinstance(node, (ast.If, ast.IfExp)):
        out += [('always', ast.Constant(True)), ('never', ast.Constant(False)),
                ('negated', ast.UnaryOp(ast.Not(), copy.deepcopy(node.test)))]
    if isinstance(node, ast.While):
        out.append(('never', ast.Constant(False)))
    if isinstance(node, ast.comprehension):
        for i, cond in enumerate(node.ifs):
            out += [(f'if{i}-always', ('ifs', i, ast.Constant(True))), (f'if{i}-never', ('ifs', i, ast.Constant(False)))]
    if isinstance(node, ast.BoolOp):
        for i in range(len(node.values)):
            out.append((f'drop{i}', ('drop', i)))
        out.append(('other-operator', ('op',)))
    if isinstance(node, ast.Compare) and len(node.ops) == 1 and _negated(node.ops[0]):
        out.append(('negated', ('cmp',)))
    if isinstance(node, ast.Return) and node.value is not None:
        value = node.value
        if isinstance(value, ast.Constant) and value.value is None:
            out.append(('answers-a-cause', ast.Constant('mutant')))
        elif isinstance(value, ast.Constant) and isinstance(value.value, bool):
            out.append(('answer-turned', ast.Constant(not value.value)))
        else:
            out.append(('answers-none', ast.Constant(None)))
    if isinstance(node, ast.Continue):
        out.append(('dropped', None))
    if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
        out.append(('dropped', None))
    if isinstance(node, ast.ExceptHandler):
        out.append(('catches-nothing', ('except',)))
    return out


def _apply(tree: ast.AST, target_index: int, change: object) -> ast.AST:
    """A copy of `tree` with the `target_index`-th node of its walk changed as `change` says."""
    tree = copy.deepcopy(tree)
    node, parent, field, index = list(_walk(tree))[target_index]
    if change is None:
        getattr(parent, field)[index] = ast.Pass()
    elif isinstance(change, ast.AST):
        if isinstance(node, ast.Return):
            node.value = change
        else:
            node.test = change
    elif change[0] == 'ifs':
        node.ifs[change[1]] = change[2]
    elif change[0] == 'drop':
        del node.values[change[1]]
        if len(node.values) == 1:
            if index is None:
                setattr(parent, field, node.values[0])
            else:
                getattr(parent, field)[index] = node.values[0]
    elif change[0] == 'op':
        node.op = ast.Or() if isinstance(node.op, ast.And) else ast.And()
    elif change[0] == 'cmp':
        node.ops = [_negated(node.ops[0])]
    elif change[0] == 'except':
        node.type = ast.Name('ZeroDivisionError', ast.Load())
    return ast.fix_missing_locations(tree)


def _walk(tree: ast.AST):
    """Every node of `tree` in a fixed order, with its parent, the field holding it and its index there."""
    stack = [(tree, None, None, None)]
    while stack:
        node, parent, field, index = stack.pop(0)
        yield node, parent, field, index
        for name, value in ast.iter_fields(node):
            if isinstance(value, list):
                stack.extend((v, node, name, i) for i, v in enumerate(value) if isinstance(v, ast.AST))
            elif isinstance(value, ast.AST):
                stack.append((value, node, name, None))


def generated() -> list[Mutant]:
    text = SOURCE.read_text()
    module = ast.parse(text)
    found: list[Mutant] = []
    for top in module.body:
        if isinstance(top, ast.FunctionDef) and top.name in FUNCTIONS:
            old = ast.get_source_segment(text, top)
            base = ast.unparse(top)
            counts: dict[str, int] = {}
            for i, (node, parent, field, index) in enumerate(_walk(top)):
                kind = type(node).__name__
                n = counts[kind] = counts.get(kind, 0) + 1
                for label, change in _variants(node, parent):
                    new = ast.unparse(_apply(top, i, change))
                    if new != base:
                        found.append(Mutant(f'{top.name}:{kind}@{n}:{label}', old, new, f'{kind} {label}'))
        elif isinstance(top, (ast.Assign, ast.AnnAssign)):
            target = top.targets[0] if isinstance(top, ast.Assign) else top.target
            if not (isinstance(target, ast.Name) and target.id in TABLES):
                continue
            old = ast.get_source_segment(text, top)
            if isinstance(top.value, ast.Tuple):
                for i, item in enumerate(top.value.elts):
                    mutated = copy.deepcopy(top)
                    del mutated.value.elts[i]
                    found.append(Mutant(f'{target.id}:drop:{ast.unparse(item)}', old, ast.unparse(mutated),
                                        'a type dropped'))
            else:
                for i, (key, value) in enumerate(zip(top.value.keys, top.value.values)):
                    if key is not None:
                        mutated = copy.deepcopy(top)
                        mutated.value.values[i] = ast.parse('lambda value, info: None', mode='eval').body
                        found.append(Mutant(f'TOOL_RULES:{key.value}:unchecked', old, ast.unparse(mutated),
                                            'a rule checks nothing'))
                    else:
                        names = value.generators[0].iter.elts
                        for j, name in enumerate(names):
                            mutated = copy.deepcopy(top)
                            del mutated.value.values[i].generators[0].iter.elts[j]
                            found.append(Mutant(f'TOOL_RULES:{name.value}:left-to-the-generic-rule', old,
                                                ast.unparse(mutated), 'a field left to the generic rule'))
                        mutated = copy.deepcopy(top)
                        mutated.value.values[i].value = ast.parse('lambda value, info: None', mode='eval').body
                        found.append(Mutant('TOOL_RULES:default-rule:unchecked', old, ast.unparse(mutated),
                                            'the default rule checks nothing'))
    for n, comment in enumerate(COMMENTS, 1):
        decision = comment + DECISION
        found.append(Mutant(f'load:decision{n}:never', decision, comment + DECISION.replace(
            'if held := _registry_violation(before):', 'if False:'), 'a decision of the registry never taken'))
        found.append(Mutant(f'load:decision{n}:always', decision, comment + DECISION.replace(
            'if held := _registry_violation(before):', "if held := 'mutant':"), 'a decision always taken'))
    ids = [m.id for m in found]
    assert len(ids) == len(set(ids)), sorted({i for i in ids if ids.count(i) > 1})
    return found


def control_edits() -> tuple[tuple[str, str], ...]:
    text = SOURCE.read_text()
    module = ast.parse(text)
    return tuple((ast.get_source_segment(text, top), ast.unparse(top)) for top in module.body
                 if isinstance(top, ast.FunctionDef) and top.name in FUNCTIONS)


CHILD = mutants.CHILD.replace('exec "$py" -m pytest -q -rA -p no:cacheprovider --junitxml="$junit" "$@"',
                              'exec "$py" -m pytest -q -x -p no:cacheprovider --junitxml="$junit" "$@"')
assert CHILD != mutants.CHILD, 'the runner child changed: the sweep\'s -x no longer applies'


def run_one(mutant_id: str, edits: tuple[tuple[str, str], ...], era: str) -> tuple[str, str, float]:
    """Plant `edits`, run the targets in `era`; return (verdict, detail, seconds)."""
    start = time.monotonic()
    with tempfile.TemporaryDirectory(prefix='f1-sweep-') as scratch:
        dest = Path(scratch)
        src = mutants.apply(mutants.Case(mutant_id, LOADER, edits, (), ''), dest)
        junit = dest / 'junit.xml'
        env = {k: v for k, v in os.environ.items() if k != 'CLUSTER_MCP_SKIP_PROBES'}
        env |= {'PYTHONPATH': str(src), 'PYTHONDONTWRITEBYTECODE': '1'}
        env.pop('CLUSTER_MCP_TEST_ERA', None)
        if ERAS[era]:
            env['CLUSTER_MCP_TEST_ERA'] = ERAS[era]
        child = subprocess.Popen([str(mutants.SANDBOX), 'sh', '-c', CHILD, 'sh', sys.executable, str(src), str(junit),
                                  str(ROOT), *TARGETS], env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                 text=True, start_new_session=True)
        try:
            out, err = child.communicate(timeout=BOUND)
        except subprocess.TimeoutExpired:
            os.killpg(child.pid, signal.SIGKILL)
            child.communicate()
            return 'timeout', f'past {BOUND} s', time.monotonic() - start
        seconds = time.monotonic() - start
        failed, errored = [], []
        if junit.exists():
            for case in ET.fromstring(junit.read_text()).iter('testcase'):
                for child_node in case:
                    if child_node.tag == 'failure':
                        failed.append((mutants._node_id(case), (child_node.get('message') or '').splitlines()[0][:160]))
                    elif child_node.tag == 'error':
                        errored.append((mutants._node_id(case), (child_node.get('message') or '').splitlines()[0][:160]))
        if child.returncode == 0:
            return 'survived', '', seconds
        if child.returncode == mutants.WRONG_ORIGIN:
            return 'harness', 'wrong import origin', seconds
        if child.returncode == 1 and failed:
            test, message = failed[0]
            return 'killed', f'{test} | {message}', seconds
        if errored:
            test, message = errored[0]
            return 'error', f'{test} | {message}', seconds
        return 'harness', f'exit {child.returncode}: {err.strip()[-200:]!r}', seconds


def shard_of(mutant_id: str, count: int) -> int:
    return zlib.crc32(mutant_id.encode()) % count


def main(argv: list[str]) -> int:
    mode = argv[0] if argv else 'list'
    found = generated()
    stale = sorted(set(EQUIVALENT) - {m.id for m in found})
    if stale:
        print(f'F1 sweep: recorded equivalents no mutant has: {stale}', file=sys.stderr)
        return 1
    if mode == 'list':
        for m in found:
            print(m.id)
        print(f'{len(found)} mutants', file=sys.stderr)
        return 0
    if mode == 'control':
        verdict, detail, seconds = run_one('f1-control', control_edits(), argv[1])
        print(f'control {argv[1]}: {verdict} {detail} ({seconds:.0f} s)')
        return 0 if verdict == 'survived' else 1
    if mode == 'run':
        era, (k, n) = argv[1], map(int, argv[2].split('/'))
        log = Path(argv[3]) if len(argv) > 3 else None
        if log:
            log.parent.mkdir(parents=True, exist_ok=True)
            log.write_text('')
        mine = [m for m in found if shard_of(m.id, n) == k - 1]
        bad = 0

        def one(m: Mutant) -> str:
            verdict, detail, seconds = run_one(m.id, ((m.old, m.new),), era)
            if verdict == 'survived' and m.id in EQUIVALENT:
                verdict, detail = 'equivalent', EQUIVALENT[m.id]
            return f'{era}\t{verdict}\t{m.id}\t{seconds:.0f}\t{detail}'

        with ThreadPoolExecutor(WORKERS) as pool:
            for line in pool.map(one, mine):
                print(line, flush=True)
                if log:
                    with log.open('a') as handle:
                        handle.write(line + '\n')
                bad += line.split('\t')[1] not in ('killed', 'equivalent')
        print(f'F1 sweep {era} {k}/{n}: {len(mine)} mutants, {bad} not killed or equivalent', file=sys.stderr)
        return 1 if bad else 0
    if mode == 'ids':
        era, wanted = argv[1], set(argv[2:])
        unknown = sorted(wanted - {m.id for m in found})
        if unknown:
            print(f'F1 sweep: no such mutant: {unknown}', file=sys.stderr)
            return 1
        bad = 0
        for m in found:
            if m.id in wanted:
                verdict, detail, seconds = run_one(m.id, ((m.old, m.new),), era)
                if verdict == 'survived' and m.id in EQUIVALENT:
                    verdict, detail = 'equivalent', EQUIVALENT[m.id]
                print(f'{era}\t{verdict}\t{m.id}\t{seconds:.0f}\t{detail}', flush=True)
                bad += verdict not in ('killed', 'equivalent')
        return 1 if bad else 0
    if mode == 'report':
        verdicts: dict[str, dict[str, str]] = {}
        for name in argv[1:]:
            for line in Path(name).read_text().splitlines():
                era, verdict, mutant_id, _, detail = line.split('\t', 4)
                verdicts.setdefault(mutant_id, {})[era] = verdict
        missing = [m.id for m in found if set(verdicts.get(m.id, {})) != set(ERAS)]
        bad = [(i, v) for i, v in verdicts.items() if any(x not in ('killed', 'equivalent') for x in v.values())]
        totals: dict[str, int] = {}
        for v in verdicts.values():
            for era, x in v.items():
                totals[f'{era} {x}'] = totals.get(f'{era} {x}', 0) + 1
        print(f'{len(found)} mutants; ' + ', '.join(f'{k}: {v}' for k, v in sorted(totals.items())))
        for mutant_id, v in bad:
            print(f'NOT KILLED  {mutant_id}: {v}')
        for mutant_id in missing:
            print(f'UNRUN       {mutant_id}: {verdicts.get(mutant_id, {})}')
        return 1 if bad or missing else 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
